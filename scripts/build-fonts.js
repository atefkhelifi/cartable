// Writes public/css/fonts.css from the @fontsource packages, so Cartable serves its own fonts
// (no request to Google Fonts). Run it again after updating those packages: npm run build-fonts
const fs = require('fs');
const path = require('path');

const FONTS = {
  'atkinson-hyperlegible': [400, 700],
  fredoka: [500, 600, 700],
  'baloo-bhaijaan-2': [500, 600, 700],
  'ibm-plex-sans-arabic': [400, 700],
};
const root = path.join(__dirname, '..');
let css = '/* Generated by scripts/build-fonts.js from @fontsource packages (SIL Open Font License). Do not edit. */\n';
for (const [pkg, weights] of Object.entries(FONTS)) {
  for (const w of weights) {
    const src = fs.readFileSync(path.join(root, 'node_modules', '@fontsource', pkg, `${w}.css`), 'utf8');
    css += src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/url\(\.\/files\//g, `url(/fonts/${pkg}/`).trim() + '\n';
  }
}
fs.writeFileSync(path.join(root, 'public', 'css', 'fonts.css'), css);
console.log(`public/css/fonts.css: ${(css.match(/@font-face/g) || []).length} font faces`);
